"""Extract the S1AP ASN.1 modules from TS 36.413 and compile them.

Run from the repository root:

    python lib/codecs/build_s1ap.py [path/to/36413-j20.docx]

S1AP is delivered as seven modules that import from each other, so all of
them are compiled together in dependency order. The text is taken from the
``-- ASN1START`` / ``-- ASN1STOP`` blocks only; a module that fails to
compile is reported, never swallowed.

Do not use the plain-text rendering of this spec as the source: in the
``36413-j20.txt`` dump that this host also holds, the PDF layout has merged
identifiers with their types and dropped some type references outright (for
example ``&InitiatingMessageWithoutItsType,``). The docx delivery keeps the
runs, and this builder reads it.

Outputs, all committed:

    lib/codecs/asn1/s1ap.asn        the seven modules, verbatim
    lib/codecs/s1ap_codec.py        the compiled Python module (pycrate)

The header of each output records the source file, the spec version and the
compiler version. Regenerate only when the source spec changes.
"""

from __future__ import annotations

import argparse
import re
import zipfile
from pathlib import Path

# Dependency order: common data types and constants first, then containers,
# the IE definitions, the PDU contents that reference them, and finally the
# PDU descriptions. SonTransfer-IEs imports from S1AP-IEs.
MODULES = (
    "S1AP-CommonDataTypes",
    "S1AP-Constants",
    "S1AP-Containers",
    "S1AP-IEs",
    "S1AP-PDU-Contents",
    "S1AP-PDU-Descriptions",
    "SonTransfer-IEs",
)

# Document artefacts in the annex, not protocol content. Kept as a list so a
# future delivery that needs a repair documents it here.
REPAIRS: tuple[tuple[str, str], ...] = ()


def paragraphs(docx: Path) -> list[str]:
    xml = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
    out: list[str] = []
    for para in re.findall(r"<w:p\b.*?</w:p>", xml, re.S):
        line = ""
        for run in re.findall(r"<w:r\b[^>]*>(.*?)</w:r>", para, re.S):
            for kind, value in re.findall(
                r"<w:(t|tab|br)\b[^>]*?(?:/>|>(.*?)</w:\1>)", run, re.S
            ):
                if kind == "t":
                    line += value
                elif kind == "tab":
                    line += " "
                else:
                    line += "\n"
        out.append(line)
    return out


def blocks(text: str) -> list[str]:
    return re.findall(r"-- ASN1START(.*?)-- ASN1STOP", text, re.S)


def module_text(all_blocks: list[str], name: str) -> str:
    header = re.compile(r"(?m)^\s*" + re.escape(name) + r"\s*$")
    start = None
    for index, block in enumerate(all_blocks):
        if header.search(block) or re.search(
                r"(?m)^\s*" + re.escape(name) + r"\s*\{", block):
            start = index
            break
    if start is None:
        raise SystemExit(f"module {name} not found in the document")
    out: list[str] = []
    for block in all_blocks[start:]:
        out.append(block.strip())
        if re.search(r"(?m)^END\s*$", block):
            return "\n\n".join(out)
    raise SystemExit(f"module {name} has no terminating END")


def build(docx: Path) -> str:
    text = "\n".join(paragraphs(docx))
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    all_blocks = blocks(text)
    body = "\n\n".join(module_text(all_blocks, name) for name in MODULES)
    for broken, fixed in REPAIRS:
        if broken not in body:
            raise SystemExit(f"repair source not found: {broken!r}")
        body = body.replace(broken, fixed)
    return body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "docx", nargs="?",
        default=r"C:\Users\KEVIN\Downloads\3gpp_specs\36.413\36413-j20.docx",
    )
    args = parser.parse_args()
    asn = build(Path(args.docx))

    from importlib.metadata import version

    from pycrate_asn1c.asnproc import compile_text
    from pycrate_asn1c.generator import PycrateGenerator
    from pycrate_asn1c.glob import GLOBAL

    GLOBAL.clear_comp_ns()
    compile_text(asn, checkconst=True)
    if GLOBAL.ERR:
        raise SystemExit(f"pycrate reported {len(GLOBAL.ERR)} errors: "
                         f"{list(GLOBAL.ERR)[:5]}")

    header = (
        "-- Generated by lib/codecs/build_s1ap.py; do not edit.\n"
        f"-- Source: TS 36.413 ASN.1, {Path(args.docx).name}\n"
        f"-- Compiler: pycrate-asn1c {version('pycrate')}\n"
        "-- Modules: " + ", ".join(MODULES) + "\n\n"
    )
    out = Path(__file__).resolve().parent / "asn1" / "s1ap.asn"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + asn + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(asn)} bytes of ASN.1)")

    codec = Path(__file__).resolve().parent / "s1ap_codec.py"
    PycrateGenerator(str(codec))
    text = codec.read_text(encoding="utf-8")
    codec.write_text(header.replace("-- ", "# ") + text, encoding="utf-8", newline="\n")
    print(f"wrote {codec} ({codec.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
