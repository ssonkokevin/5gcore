"""Extract the LCS-AP ASN.1 modules from TS 29.171 and compile them.

Run from the repository root:

    python lib/codecs/build_lcsap.py [path/to/29171-j10.docx]

The docx is the published 3GPP delivery; the ASN.1 annex is formatted in
proportional runs, so the text is rebuilt run by run (a tab is a space, a run
boundary is not). Two places in the annex are repaired, both document
artefacts rather than protocol content; they are listed in REPAIRS below and a
compile failure is reported, never swallowed.

Outputs, all committed:

    lib/codecs/asn1/lcsap.asn       the six modules, verbatim except REPAIRS
    lib/codecs/lcsap_codec.py       the compiled Python module (pycrate)

The header of each output records the source file, the spec version and the
compiler version. Regenerate only when the source spec changes.
"""

from __future__ import annotations

import argparse
import re
import zipfile
from pathlib import Path

MODULES = (
    "LCS-AP-PDU-Descriptions",
    "LCS-AP-PDU-Contents",
    "LCS-AP-IEs",
    "LCS-AP-CommonDataTypes",
    "LCS-AP-Constants",
    "LCS-AP-Containers",
)

# Document artefacts in the annex, not protocol content.
# 1. One object-set entry was typed as "High-Accuracy-" + "Accuracy-Ellipsoid-...".
#    The type it names exists once; the duplicated fragment is a tracked-change
#    residue in the published docx.
REPAIRS = (
    ("High-Accuracy- Accuracy-Ellipsoid-Point-With-Altitude-And-Scalable"
     "-Uncertainty-Ellipsoid",
     "High-Accuracy-Ellipsoid-Point-With-Altitude-And-Scalable"
     "-Uncertainty-Ellipsoid"),
)


def paragraphs(docx: Path) -> list[str]:
    xml = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
    out: list[str] = []
    for para in re.findall(r"<w:p\b.*?</w:p>", xml, re.S):
        line = ""
        for run in re.findall(r"<w:r\b[^>]*>(.*?)</w:r>", para, re.S):
            for kind, value in re.findall(
                r"<w:(t|tab|br)\b[^>]*?(?:/>|>(.*?)</w:\1>)", run, re.S
            ):
                if kind == "t":
                    line += value
                elif kind == "tab":
                    line += " "
                else:
                    line += "\n"
        out.append(line)
    return out


def module_text(lines: list[str], name: str) -> str:
    text = "\n".join(lines)
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    start = text.find(name + " {")
    if start < 0:
        raise SystemExit(f"module {name} not found in the document")
    end = text.find("\nEND", start)
    if end < 0:
        raise SystemExit(f"module {name} has no END")
    return text[start:end + 4]


def build(docx: Path) -> str:
    lines = paragraphs(docx)
    body = "\n\n".join(module_text(lines, name) for name in MODULES)
    for broken, fixed in REPAIRS:
        if broken in body:
            body = body.replace(broken, fixed)
    return body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "docx", nargs="?",
        default=r"C:\Users\KEVIN\Downloads\lcsap\29171-j10.docx",
    )
    args = parser.parse_args()
    asn = build(Path(args.docx))

    from importlib.metadata import version

    from pycrate_asn1c.asnproc import compile_text
    from pycrate_asn1c.generator import PycrateGenerator
    from pycrate_asn1c.glob import GLOBAL

    GLOBAL.clear_comp_ns()
    compile_text(asn, checkconst=True)
    header = (
        "-- Generated by lib/codecs/build_lcsap.py; do not edit.\n"
        f"-- Source: TS 29.171 ASN.1 annex, {Path(args.docx).name}\n"
        f"-- Compiler: pycrate-asn1c {version('pycrate')}\n"
        "-- Modules: " + ", ".join(MODULES) + "\n\n"
    )
    out = Path(__file__).resolve().parent / "asn1" / "lcsap.asn"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + asn + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(asn)} bytes of ASN.1)")

    codec = Path(__file__).resolve().parent / "lcsap_codec.py"
    PycrateGenerator(str(codec))
    text = codec.read_text(encoding="utf-8")
    codec.write_text(header.replace("-- ", "# ") + text, encoding="utf-8", newline="\n")
    print(f"wrote {codec} ({codec.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
