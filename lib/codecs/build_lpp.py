"""Extract the LPP ASN.1 modules from TS 37.355 and compile them.

Run from the repository root:

    python lib/codecs/build_lpp.py [path/to/37355-j30.docx]

The docx is the published 3GPP delivery. Unlike the LCS-AP annex, the LPP
annex interleaves prose with the abstract syntax, so the text is taken from
the ``-- ASN1START`` / ``-- ASN1STOP`` blocks only, run by run. A block that
fails to compile is reported, never swallowed.

Outputs, all committed:

    lib/codecs/asn1/lpp.asn         the two modules, verbatim
    lib/codecs/lpp_codec.py         the compiled Python module (pycrate)

The header of each output records the source file, the spec version and the
compiler version. Regenerate only when the source spec changes.
"""

from __future__ import annotations

import argparse
import re
import zipfile
from pathlib import Path

MODULES = (
    "LPP-PDU-Definitions",
    "LPP-Broadcast-Definitions",
)

# Document artefacts in the annex, not protocol content. Kept as a list so a
# future delivery that needs a repair documents it here.
REPAIRS: tuple[tuple[str, str], ...] = ()


def paragraphs(docx: Path) -> list[str]:
    xml = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
    out: list[str] = []
    for para in re.findall(r"<w:p\b.*?</w:p>", xml, re.S):
        line = ""
        for run in re.findall(r"<w:r\b[^>]*>(.*?)</w:r>", para, re.S):
            for kind, value in re.findall(
                r"<w:(t|tab|br)\b[^>]*?(?:/>|>(.*?)</w:\1>)", run, re.S
            ):
                if kind == "t":
                    line += value
                elif kind == "tab":
                    line += " "
                else:
                    line += "\n"
        out.append(line)
    return out


def module_text(text: str, name: str) -> str:
    header = re.search(
        re.escape(name) + r"\s+DEFINITIONS\s+AUTOMATIC\s+TAGS\s*::=", text
    )
    if header is None:
        raise SystemExit(f"module {name} not found in the document")
    first = text.rfind("-- ASN1START", 0, header.start())
    if first < 0:
        raise SystemExit(f"module {name} has no ASN1START before its header")
    end = re.compile(r"-- ASN1START\s*\n\s*END\s*\n\s*-- ASN1STOP").search(text, first)
    if end is None:
        raise SystemExit(f"module {name} has no terminating END block")
    # The block that opens with the module header carries BEGIN; the block
    # that terminates the module carries END. Everything between is syntax.
    blocks = re.findall(r"-- ASN1START(.*?)-- ASN1STOP",
                        text[first:end.end()], re.S)
    return "\n\n".join(block.strip() for block in blocks)


def build(docx: Path) -> str:
    text = "\n".join(paragraphs(docx))
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    body = "\n\n".join(module_text(text, name) for name in MODULES)
    for broken, fixed in REPAIRS:
        if broken in body:
            body = body.replace(broken, fixed)
    return body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "docx", nargs="?",
        default=r"C:\Users\KEVIN\Downloads\3gpp_specs\37.355\37355-j30.docx",
    )
    args = parser.parse_args()
    asn = build(Path(args.docx))

    from importlib.metadata import version

    from pycrate_asn1c.asnproc import compile_text
    from pycrate_asn1c.generator import PycrateGenerator
    from pycrate_asn1c.glob import GLOBAL

    GLOBAL.clear_comp_ns()
    compile_text(asn, checkconst=True)
    if GLOBAL.ERR:
        raise SystemExit(f"pycrate reported {len(GLOBAL.ERR)} errors: "
                         f"{list(GLOBAL.ERR)[:5]}")

    header = (
        "-- Generated by lib/codecs/build_lpp.py; do not edit.\n"
        f"-- Source: TS 37.355 ASN.1, {Path(args.docx).name}\n"
        f"-- Compiler: pycrate-asn1c {version('pycrate')}\n"
        "-- Modules: " + ", ".join(MODULES) + "\n\n"
    )
    out = Path(__file__).resolve().parent / "asn1" / "lpp.asn"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + asn + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(asn)} bytes of ASN.1)")

    codec = Path(__file__).resolve().parent / "lpp_codec.py"
    PycrateGenerator(str(codec))
    text = codec.read_text(encoding="utf-8")
    codec.write_text(header.replace("-- ", "# ") + text, encoding="utf-8", newline="\n")
    print(f"wrote {codec} ({codec.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
